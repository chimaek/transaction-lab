export function termsIn(text) {
  let rest = text;
  const found = [];
  for (const entry of glossary) {
    if (rest.includes(entry[0])) {
      found.push({ word: entry[0], text: entry[1] });
      rest = rest.split(entry[0]).join("\u0000");
    }
  }
  return found;
}
